'use strict';
// Independent saved editions using existing image fixtures; never calls generation.
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { createAtlas } = require('../lib/atlas.cjs');
const { createStudio } = require('../lib/design-studio.cjs');
const { loadCatalog } = require('../lib/design-studio-content.cjs');
const { makeServer } = require('../server.cjs');
const root = path.resolve(__dirname, '..'), temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'orbit-studio-comparison-'));
const catalog = loadCatalog(root), dataRoot = path.join(temporary, 'studio'), oldId = '17556e5d-dae0-453e-a6a8-6d0c45254d63', newId = 'ds003-editorial-v2';
const original = structuredClone(catalog.topics.find(t => t.id === 'DS003'));
original.caption = '原版作品的已保存文案，与当前选题稿分开保留。';
const revised = { ...structuredClone(original), schemaVersion: 2, variantLabel: '六图编辑版', compareWithJobId: oldId, title: '包已经很努力了，水杯另想办法', caption: '新版保存稿：给手机、钥匙和一本薄书安排位置。\n\n这一版先选了薄，水杯暂时另想办法。', pages: ['cover', 'design', 'detail', 'interior', 'styling', 'journal'].map((role, i) => ({ role, title: ['一只薄包的日常', '设计档案', '细节里的心思', '内部安排', '两套通勤搭配', '设计日记'][i], filename: `${String(i + 1).padStart(2, '0')}_${role}.png`, focus: '隔离测试页面：使用真实样稿图片验证六页界面与保存稿展示。', prompt: `独立六图保存稿，第 ${i + 1} 页，角色 ${role}。参数仅为概念设计拟定，未打样。` })) };
revised.design.specs = [{ label: '外尺寸', value: '32 × 22 × 5', unit: 'cm', status: 'design-target', sourceNote: '本次拟定，未打样，非原版实测' }, { label: '肩带宽', value: 3.5, unit: 'cm', status: 'design-target', sourceNote: '设计拟定参数，待实物核对' }];
fs.mkdirSync(path.join(dataRoot, 'jobs'), { recursive: true });
for (const [id, snapshot, createdAt] of [[oldId, original, '2026-10-18T10:00:00Z'], [newId, revised, '2026-10-18T11:00:00Z']]) {
  const project = path.join(dataRoot, 'works', id);
  fs.mkdirSync(project, { recursive: true });
  const fixtures = ['01_cover.png', '02_detail.png', '03_function.png', '04_scene.png'];
  snapshot.pages.forEach((p, i) => fs.copyFileSync(path.join(root, 'data', 'design-studio', 'works', 'sample-bookstore', fixtures[i % fixtures.length]), path.join(project, p.filename)));
  fs.writeFileSync(path.join(dataRoot, 'jobs', `${id}.json`), JSON.stringify({ id, topicId: 'DS003', title: snapshot.title, snapshot, project, status: 'ready', createdAt, events: [] }));
}
const atlas = createAtlas({ root, dataRoot: path.join(temporary, 'atlas'), detect: async () => ({ available: true }) });
const studio = createStudio({ root, catalog, dataRoot, sampleDir: null, detect: async () => ({ available: true }), exportAccess: async () => {}, launch: () => { throw new Error('This test must never generate images'); } });
const server = makeServer({ atlas, studio });
(async () => {
  let browser;
  try {
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const base = `http://127.0.0.1:${server.address().port}`, artifacts = path.join(root, 'artifacts');
    fs.mkdirSync(artifacts, { recursive: true });
    browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
    const page = await browser.newPage({ viewport: { width: 1512, height: 1050 }, reducedMotion: 'reduce' }), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: async text => window.__testClipboard = text }, configurable: true }));
    await page.goto(`${base}/#design-studio?view=compare&topic=DS003&job=${newId}`);
    await page.locator('[data-ds-version=new]').waitFor();
    assert.equal(await page.locator('[data-ds-version=original] .ds-compare-preview').count(), 4);
    assert.equal(await page.locator('[data-ds-version=new] .ds-compare-preview').count(), 6);
    assert.equal(await page.locator('[data-ds-field],[data-ds-prompt],[data-ds=save],[data-ds=generate]').count(), 0);
    assert.equal(await page.locator('.ds-caption-text').count(), 2);
    assert.match(await page.locator('.ds-caption-comparison').innerText(), /原版作品的已保存文案/);
    assert.match(await page.locator('.ds-caption-comparison').innerText(), /新版保存稿/);
    await page.locator(`[data-ds=copy-job-caption][data-ds-job="${oldId}"]`).click();
    assert.match(await page.evaluate(() => window.__testClipboard), /原版作品的已保存文案/);
    await page.locator(`[data-ds=copy-job-caption][data-ds-job="${newId}"]`).click();
    assert.match(await page.evaluate(() => window.__testClipboard), /新版保存稿/);
    await page.locator(`[data-ds=copy-job-prompts][data-ds-job="${newId}"]`).click();
    const prompts = await page.evaluate(() => window.__testClipboard);
    assert.match(prompts, /第 1 页/); assert.match(prompts, /第 6 页/);
    const lastPage = page.locator('[data-ds-version=new] .ds-compare-image').last();
    await lastPage.locator('summary').click();
    assert.equal(await lastPage.locator('textarea').getAttribute('readonly'), '');
    await lastPage.locator('[data-ds=copy-job-page]').click();
    assert.equal(await page.evaluate(() => window.__testClipboard), revised.pages[5].prompt);
    await lastPage.locator('summary').click();
    await page.locator('[data-ds-version=new] .ds-compare-preview').last().click();
    await page.locator('.ds-preview-size').filter({ hasText: '1086 × 1448' }).waitFor();
    await page.getByRole('button', { name: '关闭预览', exact: true }).click();
    const savedImagePromise = page.waitForEvent('download');
    await page.getByRole('link', { name: '下载六图编辑版第6张图', exact: true }).click();
    const savedImage = await savedImagePromise; assert.equal(savedImage.suggestedFilename(), '06_journal.png');
    const exportPromise = page.waitForEvent('download');
    await page.locator(`[data-ds=export-job][data-ds-job="${newId}"]`).click();
    const exported = await exportPromise, file = path.join(temporary, 'edition.json'); await exported.saveAs(file);
    assert.equal(JSON.parse(fs.readFileSync(file, 'utf8')).pages.length, 6);
    await page.reload(); await page.locator('[data-ds-version=new]').waitFor();
    await page.locator('[data-ds-version=new] .ds-compare-preview').last().scrollIntoViewIfNeeded();
    await page.waitForFunction(() => [...document.querySelectorAll('.ds-compare-preview img')].every(im => im.complete && im.naturalWidth >= 768));
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(artifacts, 'design-studio-comparison.png'), fullPage: true });
    for (const width of [1024, 768, 390]) { await page.setViewportSize({ width, height: 1000 }); assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, 'Comparison overflow at ' + width); }
    await page.screenshot({ path: path.join(artifacts, 'design-studio-comparison-mobile.png'), fullPage: true });
    await page.locator('[data-ds-version=new] [data-ds-topic=DS003]').click();
    await page.locator('.ds-snapshot-layout').waitFor();
    assert.equal(await page.locator('[data-ds-snapshot-prompt]').count(), 6);
    assert.equal(await page.locator('[data-ds-field],[data-ds-prompt],[data-ds=save],[data-ds=generate]').count(), 0);
    assert.equal(await page.locator('.ds-generated-images img').count(), 6);
    assert.match(await page.locator('.ds-snapshot-layout').innerText(), /新版保存稿/);
    const archiveText = await page.locator('.ds-design-archive').innerText();
    assert.match(archiveText, /设计拟定参数/); assert.match(archiveText, /外尺寸：32 × 22 × 5 cm/); assert.match(archiveText, /肩带宽：3\.5 cm/);
    assert.match(archiveText, /状态：设计拟定/); assert.match(archiveText, /来源说明：本次拟定，未打样，非原版实测/);
    assert.doesNotMatch(archiveText, /specs|label|value|status|sourceNote|design-target/);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, 'Snapshot mobile overflow');
    await page.locator('[data-ds=back]').click();
    assert.equal(await page.locator('.ds-work-card').count(), 2);
    assert.equal(await page.locator('[data-ds-compare]').count(), 2);
    await page.locator('[data-ds-compare]').first().click(); assert.match(page.url(), /view=compare/);
    await page.evaluate(() => { location.hash = '#design-studio?view=topics&topic=DS003'; });
    await page.locator('[data-ds-field=title]').waitFor();
    assert.equal(await page.locator('[data-ds-prompt]').count(), 4);
    assert.equal(await page.locator('.ds-generated-images img').count(), 4);
    assert.equal(await page.locator('[data-ds=generate]').count(), 1);
    assert.equal(studio.topic('DS003').caption, catalog.topics.find(t => t.id === 'DS003').caption);
    assert.deepEqual(errors, []);
    console.log('PASS: direct 4/6 edition comparison, snapshot captions/prompts, copy/download/export, original draft preserved, six-page read-only detail, discoverable entry and mobile layouts.');
  } finally {
    await studio.close(); await atlas.close(); if (browser) await browser.close(); await new Promise(resolve => server.close(resolve));
    assert.equal(path.dirname(temporary), os.tmpdir()); assert.ok(path.basename(temporary).startsWith('orbit-studio-comparison-')); fs.rmSync(temporary, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
